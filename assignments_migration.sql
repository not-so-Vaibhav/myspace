-- ============================================================
-- 1. Create assignments table
-- ============================================================
CREATE TABLE IF NOT EXISTS public.assignments (
  id bigint generated by default as identity primary key,
  course_id bigint references public.courses(id) on delete cascade not null,
  title text not null,
  description text,
  due_date timestamptz,
  type text check (type in ('assignment', 'quiz')) not null default 'assignment',
  created_by uuid references auth.users(id) not null,
  created_at timestamptz default now() not null
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_assignments_course_id ON public.assignments(course_id);
CREATE INDEX IF NOT EXISTS idx_assignments_due_date ON public.assignments(due_date);

-- Enable RLS
ALTER TABLE public.assignments ENABLE ROW LEVEL SECURITY;

-- RLS Policies
-- SELECT: Students view assignments for enrolled courses, Instructors view own courses
CREATE POLICY "View assignments"
  ON public.assignments FOR SELECT
  USING (
    -- Instructor of the course
    EXISTS (
      SELECT 1 FROM public.courses c
      WHERE c.id = assignments.course_id
      AND c.instructor_id = auth.uid()
    )
    OR
    -- Student enrolled in the course
    EXISTS (
      SELECT 1 FROM public.enrollments e
      WHERE e.course_id = assignments.course_id
      AND e.user_id = auth.uid()
    )
  );

-- INSERT/UPDATE/DELETE: Only Instructors of the course
CREATE POLICY "Manage assignments"
  ON public.assignments FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM public.courses c
      WHERE c.id = assignments.course_id
      AND c.instructor_id = auth.uid()
    )
  );


-- ============================================================
-- 2. Create assignment_questions table (for Quizzes)
-- ============================================================
CREATE TABLE IF NOT EXISTS public.assignment_questions (
  id bigint generated by default as identity primary key,
  assignment_id bigint references public.assignments(id) on delete cascade not null,
  question_text text not null,
  options jsonb not null default '[]'::jsonb, -- Array of options for MCQ
  correct_answer text not null, -- Store correct option value/id
  marks integer default 1,
  created_at timestamptz default now() not null
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_questions_assignment_id ON public.assignment_questions(assignment_id);

-- Enable RLS
ALTER TABLE public.assignment_questions ENABLE ROW LEVEL SECURITY;

-- RLS Policies
-- SELECT: Students view questions (but NOT answers ideally, handled in API or frontend logic usually, 
-- but strict RLS here allows students to see questions if they can see assignment)
CREATE POLICY "View questions"
  ON public.assignment_questions FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM public.assignments a
      WHERE a.id = assignment_questions.assignment_id
      AND (
        -- Instructor
        EXISTS (
          SELECT 1 FROM public.courses c
          WHERE c.id = a.course_id
          AND c.instructor_id = auth.uid()
        )
        OR
        -- Student enrolled
        EXISTS (
          SELECT 1 FROM public.enrollments e
          WHERE e.course_id = a.course_id
          AND e.user_id = auth.uid()
        )
      )
    )
  );

-- INSERT/UPDATE/DELETE: Only Instructors
CREATE POLICY "Manage questions"
  ON public.assignment_questions FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM public.assignments a
      JOIN public.courses c ON c.id = a.course_id
      WHERE a.id = assignment_questions.assignment_id
      AND c.instructor_id = auth.uid()
    )
  );

-- ============================================================
-- 3. Create submissions table
-- ============================================================
CREATE TABLE IF NOT EXISTS public.submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint references public.assignments(id) on delete cascade not null,
  student_id uuid references auth.users(id) not null,
  submission_url text, -- For file uploads
  quiz_answers jsonb, -- For quiz answers: { question_id: answer }
  grade numeric,
  feedback text,
  submitted_at timestamptz default now() not null,
  graded_at timestamptz,
  
  -- Ensure one submission per student per assignment
  UNIQUE(assignment_id, student_id)
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_submissions_assignment_id ON public.submissions(assignment_id);
CREATE INDEX IF NOT EXISTS idx_submissions_student_id ON public.submissions(student_id);

-- Enable RLS
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;

-- RLS Policies
-- SELECT: Students view own, Instructors view all for their assignments
CREATE POLICY "View submissions"
  ON public.submissions FOR SELECT
  USING (
    -- Student viewing own
    student_id = auth.uid()
    OR
    -- Instructor viewing submissions for their assignments
    EXISTS (
      SELECT 1 FROM public.assignments a
      JOIN public.courses c ON c.id = a.course_id
      WHERE a.id = submissions.assignment_id
      AND c.instructor_id = auth.uid()
    )
  );

-- INSERT: Students can submit to assignments they have access to
CREATE POLICY "Create submission"
  ON public.submissions FOR INSERT
  WITH CHECK (
    student_id = auth.uid()
    AND
    EXISTS (
      SELECT 1 FROM public.assignments a
      WHERE a.id = submissions.assignment_id
      AND EXISTS (
        SELECT 1 FROM public.enrollments e
        WHERE e.course_id = a.course_id
        AND e.user_id = auth.uid()
      )
    )
  );

-- UPDATE: 
-- Students can update ONLY if not graded (optional logic, kept simple here to allow resubmission if needed, or block in frontend)
-- Instructors can update (grade/feedback)
CREATE POLICY "Update submission"
  ON public.submissions FOR UPDATE
  USING (
    -- Student updating own (e.g. resubmit)
    student_id = auth.uid()
    OR
    -- Instructor grading
    EXISTS (
      SELECT 1 FROM public.assignments a
      JOIN public.courses c ON c.id = a.course_id
      WHERE a.id = submissions.assignment_id
      AND c.instructor_id = auth.uid()
    )
  );

